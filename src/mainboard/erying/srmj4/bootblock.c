/*
 * SIO init: program only superiotool "diffs" (registers where vendor value
 * != POR default). Generated from util/gather_board_data/superiotool_dump_to_bootblock.py
 * using srmj4_board_data.json superiotool dump. HWM (0x0b) excluded; devicetree
 * + devicetree chip config (fan/PECI) configure it. Re-run script after updating dump.
 */

#include <bootblock_common.h>
#include <device/pnp_ops.h>
#include <device/pnp_type.h>
#include <superio/nuvoton/common/nuvoton.h>
#include <superio/nuvoton/nct6791d/nct6791d.h>

#define SERIAL_DEV   PNP_DEV(0x2e, NCT6791D_SP1)
#define P80_UART_DEV PNP_DEV(0x2e, NCT6791D_PORT80)

void bootblock_mainboard_early_init(void)
{
	nuvoton_pnp_enter_conf_state(P80_UART_DEV);

	/* Register dump (global config, 0x0b selected) - diffs only */
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x07, 0x0b);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x1b, 0x00);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x21, 0x2a);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x26, 0x00);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x27, 0x00);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x2a, 0x02);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x2b, 0x0c);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x2c, 0x20);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x2d, 0x30);
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0x2f, 0x04);
	/* LDN 0x05 KBC - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x05));
	pnp_write_config(PNP_DEV(0x2e, 0x05), 0x30, 0x01);
	pnp_write_config(PNP_DEV(0x2e, 0x05), 0x61, 0x60);
	pnp_write_config(PNP_DEV(0x2e, 0x05), 0x63, 0x64);
	pnp_write_config(PNP_DEV(0x2e, 0x05), 0x70, 0x01);
	pnp_write_config(PNP_DEV(0x2e, 0x05), 0x72, 0x0c);
	/* LDN 0x07 GPIO678 - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x07));
	pnp_write_config(PNP_DEV(0x2e, 0x07), 0x30, 0x0a);
	pnp_write_config(PNP_DEV(0x2e, 0x07), 0xe0, 0xfe);
	pnp_write_config(PNP_DEV(0x2e, 0x07), 0xe1, 0x97);
	/* LDN 0x08 WDT1/GPIO01 - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x08));
	pnp_write_config(PNP_DEV(0x2e, 0x08), 0x60, 0x0a);
	/* LDN 0x09 GPIO2345 - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x09));
	pnp_write_config(PNP_DEV(0x2e, 0x09), 0x30, 0x03);
	pnp_write_config(PNP_DEV(0x2e, 0x09), 0xe0, 0xdf);
	pnp_write_config(PNP_DEV(0x2e, 0x09), 0xe1, 0xf0);
	pnp_write_config(PNP_DEV(0x2e, 0x09), 0xe4, 0xf3);
	pnp_write_config(PNP_DEV(0x2e, 0x09), 0xe5, 0x78);
	pnp_write_config(PNP_DEV(0x2e, 0x09), 0xea, 0x08);
	/* LDN 0x0a ACPI - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x0a));
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xe0, 0x65);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xe5, 0x00);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xe6, 0x0a);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xe7, 0x10);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xec, 0x80);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xee, 0x40);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xf2, 0xdf);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xf3, 0x30);
	pnp_write_config(PNP_DEV(0x2e, 0x0a), 0xf6, 0x30);
	/* LDN 0x0e CIR Wake-up - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x0e));
	pnp_write_config(PNP_DEV(0x2e, 0x0e), 0x60, 0x0a);
	pnp_write_config(PNP_DEV(0x2e, 0x0e), 0x61, 0x10);
	pnp_write_config(PNP_DEV(0x2e, 0x0e), 0xf4, 0x10);
	/* LDN 0x0f GPIO PP/OD - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x0f));
	pnp_write_config(PNP_DEV(0x2e, 0x0f), 0xe1, 0xdf);
	pnp_write_config(PNP_DEV(0x2e, 0x0f), 0xe6, 0xfe);
	pnp_write_config(PNP_DEV(0x2e, 0x0f), 0xf1, 0x00);
	/* LDN 0x11 PGPIO - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x11));
	pnp_write_config(PNP_DEV(0x2e, 0x11), 0xe2, 0x02);
	/* LDN 0x12 LED - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x12));
	pnp_write_config(PNP_DEV(0x2e, 0x12), 0xe0, 0x10);
	pnp_write_config(PNP_DEV(0x2e, 0x12), 0xe6, 0x80);
	pnp_write_config(PNP_DEV(0x2e, 0x12), 0xe7, 0x20);
	pnp_write_config(PNP_DEV(0x2e, 0x12), 0xea, 0x00);
	pnp_write_config(PNP_DEV(0x2e, 0x12), 0xeb, 0x3c);
	pnp_write_config(PNP_DEV(0x2e, 0x12), 0xef, 0x00);
	/* LDN 0x14 Port 80 - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x14));
	pnp_write_config(PNP_DEV(0x2e, 0x14), 0xe4, 0xa0);
	/* LDN 0x16 Deep Sleep - diffs only */
	pnp_set_logical_device(PNP_DEV(0x2e, 0x16));
	pnp_write_config(PNP_DEV(0x2e, 0x16), 0xf5, 0x82);
	pnp_write_config(PNP_DEV(0x2e, 0x16), 0xf8, 0x60);

	nuvoton_pnp_exit_conf_state(P80_UART_DEV);

	if (CONFIG(CONSOLE_SERIAL))
		nuvoton_enable_serial(SERIAL_DEV, CONFIG_TTYS0_BASE);
}
